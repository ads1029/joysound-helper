export const kanjiVariantTable: Readonly<Record<string, string>> =
  Object.freeze(
    Object.fromEntries(
      kanjiVariantGroups.flatMap((group) => {
        const [canonical] = Array.from(group);
        return Array.from(group).map((variant) => [variant, canonical]);
      }),
    ),
  );

export function normalizeKanjiVariants(value: string): string {
  return Array.from(value, (character) => {
    return kanjiVariantTable[character] ?? character;
  }).join("");
}
